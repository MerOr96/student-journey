const FORM_LABELS: Record<string, string> = {
  o: 'Очная',
  oz: 'Очно-заочная',
};

// Строим нормализованный список с числовыми ID
let specialtyCounter = 1;

export const FACULTIES: Faculty[] = RAW.map((f, fi) => ({
  id: fi + 1,
  name: f.name,
  specialties: f.specialties.map((s) => {
    const dashIdx = s[0].indexOf(' ');
    return {
      id: specialtyCounter++,
      code: dashIdx > -1 ? s[0].substring(0, dashIdx) : s[0],
      name: s[0],
      form: s[1],
      formLabel: FORM_LABELS[s[1]] ?? s[1],
      facultyId: fi + 1,
    };
  }),
}));

export const ALL_SPECIALTIES: Specialty[] = FACULTIES.flatMap((f) => f.specialties);
